///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Mesen2 SMS Core Plugin - Wrapper around Mesen2 Master System/Game Gear emulator
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include "mesen2_shared.h"
#include "Core/SMS/SmsConsole.h"

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// SMS system configuration

static const Mesen2SystemInfo s_sms_info = {
    .emu_name = "Mesen2",
    .system_name = "Sega Master System / Game Gear",
    .extensions = "sms|gg|sg|col",
    .requires_bios = false,
    .default_width = 256,
    .default_height = 192,
    .default_fps = 59.922751f,
    .cpu_type = CpuType::Sms,
    .visible_x = 0,
    .visible_y = 0,
    .visible_width = 256,
    .visible_height = 192,
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_get_info(RpEmuInfo* info) {
    info->emu_name = s_sms_info.emu_name;
    info->emu_version = "2.0";
    info->system_name = s_sms_info.system_name;
    info->supported_extensions = s_sms_info.extensions;
    info->requires_bios = s_sms_info.requires_bios;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void* mesen2_sms_create(FlArena* arena) {
    return mesen2_create_core(arena, s_sms_info, "SMS/Game Gear");
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_destroy(void* ci) {
    mesen2_destroy_core((Mesen2CoreBase*)ci, "SMS");
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static bool mesen2_sms_mount_media(void* ci, const char* path) {
    return mesen2_mount_media((Mesen2CoreBase*)ci, path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_unmount_media(void* ci) {
    mesen2_unmount_media((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_run_frame(void* ci, RpEmuFrameContext* ctx) {
    mesen2_run_frame((Mesen2CoreBase*)ci, ctx);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_reset(void* ci) {
    mesen2_reset((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_hard_reset(void* ci) {
    mesen2_hard_reset((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_get_video_spec(void* ci, RpVideoSpec* spec) {
    mesen2_get_video_spec((Mesen2CoreBase*)ci, spec);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_sms_get_audio_spec(void* ci, RpAudioSpec* spec) {
    (void)ci;
    mesen2_get_audio_spec(spec);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static RpEmuLifecycleState mesen2_sms_get_state(void* ci) {
    return mesen2_get_state((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static size_t mesen2_sms_serialize(void* ci, void* b, size_t bs) {
    (void)ci;
    (void)b;
    (void)bs;
    return 0;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static bool mesen2_sms_deserialize(void* ci, const void* b, size_t bs) {
    (void)ci;
    (void)b;
    (void)bs;
    return false;
}

