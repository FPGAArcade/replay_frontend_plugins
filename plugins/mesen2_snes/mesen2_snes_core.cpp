///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// Mesen2 SNES Core Plugin - Wrapper around Mesen2 SNES emulator
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

#include "mesen2_shared.h"
#include "Core/SNES/SnesConsole.h"

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
// SNES system configuration

static const Mesen2SystemInfo s_snes_info = {
    .emu_name = "Mesen2",
    .system_name = "Super Nintendo Entertainment System",
    .extensions = "sfc|swc|fig|smc|bs|spc",
    .requires_bios = false,
    .default_width = 256,
    .default_height = 224,
    .default_fps = 60.098812f,
    .cpu_type = CpuType::Snes,
    .visible_x = 0,
    .visible_y = 0,
    .visible_width = 256,
    .visible_height = 224,
};

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_get_info(RpEmuInfo* info) {
    info->emu_name = s_snes_info.emu_name;
    info->emu_version = "2.0";
    info->system_name = s_snes_info.system_name;
    info->supported_extensions = s_snes_info.extensions;
    info->requires_bios = s_snes_info.requires_bios;
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void* mesen2_snes_create(FlArena* arena) {
    return mesen2_create_core(arena, s_snes_info, "SNES");
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_destroy(void* ci) {
    mesen2_destroy_core((Mesen2CoreBase*)ci, "SNES");
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static bool mesen2_snes_mount_media(void* ci, const char* path) {
    return mesen2_mount_media((Mesen2CoreBase*)ci, path);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_unmount_media(void* ci) {
    mesen2_unmount_media((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_run_frame(void* ci, RpEmuFrameContext* ctx) {
    mesen2_run_frame((Mesen2CoreBase*)ci, ctx);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_reset(void* ci) {
    mesen2_reset((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_hard_reset(void* ci) {
    mesen2_hard_reset((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_get_video_spec(void* ci, RpVideoSpec* spec) {
    mesen2_get_video_spec((Mesen2CoreBase*)ci, spec);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static void mesen2_snes_get_audio_spec(void* ci, RpAudioSpec* spec) {
    (void)ci;
    mesen2_get_audio_spec(spec);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static RpEmuLifecycleState mesen2_snes_get_state(void* ci) {
    return mesen2_get_state((Mesen2CoreBase*)ci);
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

